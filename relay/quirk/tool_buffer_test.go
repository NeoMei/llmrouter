func intPtr(v int) *int { return &v }

func TestToolCallBuffer_SingleCallSplitAcrossChunks(t *testing.T) {
	b := NewToolCallBuffer()

	// 分片 1: name + id (index=0)
	b.Accumulate([]dto.ToolCallResponse{{
		Index: intPtr(0),
		ID:    "call_1",
		Function: dto.FunctionResponse{
			Name: "calc",
		},
	}})
	// 分片 2: arguments 第一段
	b.Accumulate([]dto.ToolCallResponse{{
		Index: intPtr(0),
		Function: dto.FunctionResponse{
			Arguments: `{"expr":`,
		},
	}})
	// 分片 3: arguments 第二段
	b.Accumulate([]dto.ToolCallResponse{{
		Index: intPtr(0),
		Function: dto.FunctionResponse{
			Arguments: ` "2+2"}`,
		},
	}})

	require.True(t, b.Has(), "buffer should have pending calls before flush")

	flushed, err := b.Flush()
	require.NoError(t, err)
	require.Len(t, flushed, 1)
	assert.Equal(t, "call_1", flushed[0].ID)
	assert.Equal(t, "calc", flushed[0].Name)
	assert.Equal(t, `{"expr": "2+2"}`, flushed[0].Args)

	assert.False(t, b.Has(), "buffer should be empty after flush")
}

func TestToolCallBuffer_AutoGeneratedID(t *testing.T) {
	b := NewToolCallBuffer()

	// 没有上游 ID，只有 index
	b.Accumulate([]dto.ToolCallResponse{{
		Index: intPtr(0),
		Function: dto.FunctionResponse{
			Name:      "search",
			Arguments: `{"query":"x"}`,
		},
	}})

	flushed, err := b.Flush()
	require.NoError(t, err)
	require.Len(t, flushed, 1)
	assert.Equal(t, "search", flushed[0].Name)
	assert.Equal(t, `{"query":"x"}`, flushed[0].Args)
	assert.NotEmpty(t, flushed[0].ID, "expected auto-generated ID")
	assert.Contains(t, flushed[0].ID, "call_gw_")
}

func TestToolCallBuffer_MultipleCallsSimultaneously(t *testing.T) {
	b := NewToolCallBuffer()

	// 两个 tool call 同时分片到达
	b.Accumulate([]dto.ToolCallResponse{
		{Index: intPtr(0), ID: "a", Function: dto.FunctionResponse{Name: "f1"}},
		{Index: intPtr(1), ID: "b", Function: dto.FunctionResponse{Name: "f2"}},
	})
	b.Accumulate([]dto.ToolCallResponse{
		{Index: intPtr(0), Function: dto.FunctionResponse{Arguments: `{"arg":1}`}},
		{Index: intPtr(1), Function: dto.FunctionResponse{Arguments: `{"arg":2}`}},
	})

	flushed, err := b.Flush()
	require.NoError(t, err)
	require.Len(t, flushed, 2)
	assert.Equal(t, "a", flushed[0].ID)
	assert.Equal(t, "f1", flushed[0].Name)
	assert.Equal(t, `{"arg":1}`, flushed[0].Args)
	assert.Equal(t, "b", flushed[1].ID)
	assert.Equal(t, "f2", flushed[1].Name)
	assert.Equal(t, `{"arg":2}`, flushed[1].Args)
}

